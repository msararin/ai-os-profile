import { test, expect } from "@playwright/test"
test("CTO and hiring readers can discover LLM and ML evidence from the public site", async ({page}) => {
  await page.goto('/')
  await expect(page.getByRole('region',{name:'LLM and ML capability areas'})).toBeVisible()
  await page.getByRole('navigation').getByRole('link',{name:'LLM & Agent Systems',exact:true}).click()
  await expect(page.getByRole('heading',{name:'My contribution and scope'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Architecture and trade-offs'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Selected evidence and limitations'})).toBeVisible()
  await page.getByRole('navigation').getByRole('link',{name:'ML & Decision Systems',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Machine Learning & Decision Systems',exact:true})).toBeVisible()
})
test("public case study retains measured proof and limitations without execution recipe", async ({ page }) => {
  const errors: string[]=[]; page.on("pageerror",error=>errors.push(error.message))
  await page.goto("/case-studies/nbo-nrt-azure-databricks")
  await expect(page.getByRole("heading",{name:"NBO / NRT Learning Journey"})).toBeVisible()
  await expect(page.getByText("4 experiments",{exact:true})).toBeVisible()
  await expect(page.getByText("Completed in two bounded phases · 2A and 2B",{exact:true})).toBeVisible()
  await expect(page.getByText(/10,000 synthetic observations/)).toBeVisible()
  await expect(page.getByText(/8,002 rows across 38,300 exact context–action pairs/)).toBeVisible()
  await expect(page.getByText(/SYNTHETIC_LEARNING_AND_MLOPS_EVIDENCE_ONLY/)).toBeVisible()
  await expect(page.getByText(/Experiment 4 is complete within its frozen local synthetic scope/)).toBeVisible()
  await expect(page.getByRole('heading',{name:'From Azure Databricks to local PySpark',exact:true})).toBeVisible()
  const results=page.locator('#experiment-4-results')
  for (const width of [1280,390]) {
    await page.setViewportSize({width,height:900})
    const details=results.locator('details')
    await expect(details).not.toHaveAttribute('open','')
    await details.locator('summary').click()
    await expect(details.locator('table')).toBeVisible()
    await expect(details.locator('tbody tr')).toHaveCount(4)
    await expect(details.getByText('+0.02684681',{exact:true})).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
    await details.locator('summary').press('Enter')
    await expect(details).not.toHaveAttribute('open','')
  }
  await page.setViewportSize({width:1280,height:900})
  await expect(page.locator('a[href*="/cockpit"], a[href*="github.com/msararin/nbo-nrt"]')).toHaveCount(0)
  await expect(page.locator("[data-experiment3-investigation-trail]")).toHaveCount(0)
  await page.getByRole("link",{name:"Home",exact:true}).click()
  await expect(page).toHaveURL(/\/$/)
  expect(errors).toEqual([])
})
test("private navigation and endpoints deny an anonymous browser", async ({ page, request }) => {
  await page.goto("/cockpit/telemetry")
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole("button",{name:"Continue with Google"})).toBeVisible()
  for(const route of ["/api/cockpit/telemetry","/api/cockpit/artifacts/unknown","/api/cockpit/search"]) expect((await request.get(route)).status()).toBe(401)
})
